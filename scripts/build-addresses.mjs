#!/usr/bin/env node
// Builds addresses.js: the house numbers that exist on each Bellevue street.
//
// Source: City of Richmond address points (ArcGIS), falling back to the
// Virginia statewide address points (VGIN). Or pass a local export:
//   node scripts/build-addresses.mjs                 # fetch from the web
//   node scripts/build-addresses.mjs --file pts.json # use a downloaded GeoJSON/Esri JSON
//
// Each house number in the output is a real address point. Nothing is generated
// from a numeric range. Review the printed counts before committing.

import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
const { STREETS, BBOX } = createRequire(import.meta.url)('../streets.config.js');

const SOURCES = [
  'https://services1.arcgis.com/k3vhq11XkBNeeOfM/ArcGIS/rest/services/Addresses_Test/FeatureServer',
  'https://gismaps.vdem.virginia.gov/arcgis/rest/services/VA_Base_Layers/VA_Address_Points/FeatureServer',
];
const LABEL_FIELDS = ['AddressLabel', 'FULLADDR', 'FullAddress', 'FULL_ADDRESS', 'ADDRESS', 'Address', 'SITE_ADDRESS'];

const ABBR = { AVENUE: 'AVE', ROAD: 'RD', DRIVE: 'DR', STREET: 'ST', WEST: 'W', EAST: 'E', NORTH: 'N', SOUTH: 'S' };
const norm = s => s.toUpperCase().replace(/\./g, '').split(/\s+/).filter(Boolean).map(w => ABBR[w] || w).join(' ');

// "1405 BELLEVUE AVE UNIT 2" -> { num: "1405", street: "BELLEVUE AVE" }
function parseLabel(label) {
  const m = String(label).trim().match(/^(\d+[A-Z]?)\s+(.+?)(?:\s+(?:UNIT|APT|STE|SUITE|BLDG|#)\b.*)?$/i);
  return m ? { num: m[1].toUpperCase(), street: norm(m[2]) } : null;
}

function labelOf(attrs) {
  for (const f of LABEL_FIELDS) if (attrs[f]) return attrs[f];
  return Object.values(attrs).find(v => typeof v === 'string' && /^\d+[A-Z]?\s+[A-Z]/i.test(v.trim()));
}

async function getJSON(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${url}`);
  const json = await res.json();
  if (json.error) throw new Error(`${json.error.message} ${url}`);
  return json;
}

async function fetchFromService(base) {
  const meta = await getJSON(`${base}?f=json`);
  const layerId = (meta.layers && meta.layers[0] && meta.layers[0].id) ?? 0;
  const [xmin, ymin, xmax, ymax] = BBOX;
  const rows = [];
  for (let offset = 0; ; offset += 1000) {
    const q = new URLSearchParams({
      where: '1=1', outFields: '*', returnGeometry: 'false', f: 'json',
      geometry: `${xmin},${ymin},${xmax},${ymax}`, geometryType: 'esriGeometryEnvelope',
      inSR: '4326', spatialRel: 'esriSpatialRelIntersects',
      resultOffset: String(offset), resultRecordCount: '1000',
    });
    const page = await getJSON(`${base}/${layerId}/query?${q}`);
    rows.push(...page.features.map(f => f.attributes));
    if (!page.exceededTransferLimit && page.features.length < 1000) break;
  }
  return rows;
}

async function loadRows(file) {
  if (file) {
    const json = JSON.parse(await readFile(file, 'utf8'));
    return { source: file, rows: json.features.map(f => f.properties || f.attributes) };
  }
  for (const base of SOURCES) {
    try {
      const rows = await fetchFromService(base);
      if (rows.length) return { source: base, rows };
      console.warn(`No rows from ${base}`);
    } catch (e) { console.warn(`Failed: ${e.message}`); }
  }
  throw new Error('No address source reachable. Download an export and pass --file.');
}

const fileArg = process.argv.indexOf('--file');
const { source, rows } = await loadRows(fileArg > 0 ? process.argv[fileArg + 1] : null);

const byKey = new Map(STREETS.map(s => [norm(s.name), s]));
const out = {}, dropped = {};
for (const s of STREETS) { out[s.name] = new Set(); dropped[s.name] = 0; }

for (const attrs of rows) {
  const p = parseLabel(labelOf(attrs) || '');
  if (!p) continue;
  const s = byKey.get(p.street);
  if (!s) continue;
  const n = parseInt(p.num, 10);
  if (s.range && (n < s.range[0] || n > s.range[1])) { dropped[s.name]++; continue; }
  out[s.name].add(p.num);
}

const streets = {};
console.log(`Source: ${source} (${rows.length} points in bounding box)\n`);
for (const s of STREETS) {
  streets[s.name] = [...out[s.name]].sort((a, b) => parseInt(a, 10) - parseInt(b, 10) || a.localeCompare(b));
  const list = streets[s.name];
  const note = dropped[s.name] ? `  (${dropped[s.name]} outside range ${s.range.join('-')})` : '';
  console.log(`${s.name.padEnd(20)} ${String(list.length).padStart(4)} houses  ${list[0] ?? '-'}..${list.at(-1) ?? '-'}${note}`);
}

const data = { generatedAt: new Date().toISOString(), source, streets };
await writeFile(new URL('../addresses.js', import.meta.url),
  `// Generated by scripts/build-addresses.mjs. Do not edit by hand.\nwindow.LUTH_ADDRESSES = ${JSON.stringify(data, null, 1)};\n`);
console.log('\nWrote addresses.js');
