#!/usr/bin/env node
// Bundles the Firebase SDK into vendor/firebase.js (global LUTH_FB) so the site needs no build step.
// Run after changing scripts/firebase-entry.js or upgrading firebase: npm install && npm run build:firebase
import { build } from 'esbuild';
await build({
  entryPoints: [new URL('./firebase-entry.js', import.meta.url).pathname],
  outfile: new URL('../vendor/firebase.js', import.meta.url).pathname,
  bundle: true, minify: true, format: 'iife', globalName: 'LUTH_FB', target: 'es2019',
  banner: { js: '// Firebase JS SDK bundle. Generated by scripts/build-firebase.mjs. Do not edit.' },
});
console.log('Wrote vendor/firebase.js');
